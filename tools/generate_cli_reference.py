#!/usr/bin/env python3
"""Generate the aggregate CLI catalog and Markdown reference from binaries."""

from __future__ import annotations

import argparse
import json
import pathlib
import subprocess
import sys

PROGRAMS = (
    "maelys-git",
    "maelys-git-agent",
    "maelys-git-executor",
    "maelys-git-shell",
    "maelys-git-hook",
)


def catalog(binary: pathlib.Path) -> dict:
    completed = subprocess.run(
        [str(binary), "describe", "--format", "json", "--compact", "--non-interactive"],
        check=True,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    if completed.stderr:
        raise RuntimeError(f"{binary.name} polluted stderr: {completed.stderr}")
    envelope = json.loads(completed.stdout)
    if envelope.get("contract") != "agent-cli/v2" or envelope.get("ok") is not True:
        raise RuntimeError(f"{binary.name} returned an incompatible envelope")
    for command in envelope["data"]["commands"]:
        if command["usage"] != command["input"]["synopsis"]:
            raise RuntimeError(f"{binary.name}:{command['id']} has synopsis drift")
    return envelope["data"]


def markdown(programs: dict[str, dict]) -> str:
    lines = [
        "<!-- GENERATED by tools/generate_cli_reference.py; do not edit manually. -->",
        "# Référence des CLI Maelys Git Core",
        "",
        "Contrat commun : `agent-cli/v2`. Pour le détail machine, exécutez",
        "`BINARY describe COMMAND_ID --format json`.",
        "",
    ]
    for name, data in programs.items():
        lines.extend((f"## `{name}`", "", "| Identifiant | Usage | Effet | Sortie | But |", "| --- | --- | --- | --- | --- |"))
        for command in data["commands"]:
            effect = command["effect"]
            if isinstance(effect, dict):
                effect = f"{effect['plan']} → {effect['apply']}"
            cells = [command["id"], command["usage"], effect, command["outputMode"], command["purpose"]]
            lines.append("| " + " | ".join(str(cell).replace("|", "\\|") for cell in cells) + " |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def update(path: pathlib.Path, contents: str, check: bool) -> bool:
    current = path.read_text() if path.exists() else None
    if check:
        if current != contents:
            print(f"generated CLI documentation is stale: {path}", file=sys.stderr)
            return False
        return True
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(contents)
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--build-dir", type=pathlib.Path, required=True)
    parser.add_argument("--output-dir", type=pathlib.Path, required=True)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    programs = {name: catalog((arguments.build_dir / name).resolve()) for name in PROGRAMS}
    aggregate = {
        "schemaVersion": 1,
        "contract": "agent-cli/v2",
        "product": "Maelys Git Core",
        "programs": programs,
    }
    json_source = json.dumps(aggregate, indent=2, sort_keys=True, ensure_ascii=True) + "\n"
    valid = update(arguments.output_dir / "cli-contract.json", json_source, arguments.check)
    valid = update(arguments.output_dir / "cli-reference.md", markdown(programs), arguments.check) and valid
    return 0 if valid else 1


if __name__ == "__main__":
    raise SystemExit(main())
